const EXCLUDED_DIRS = ['node_modules', 'dist', '.git', '.next', 'build', '.venv', 'venv', '__pycache__', '.tox'];

export function detectTypos(commits: Commit[], repoPath: string = process.cwd()): TypoResult[] {
  const results: TypoResult[] = [];
  const analyzedFiles = new Set<string>();
  const codeExtensions = new Set([
    '.ts', '.tsx', '.js', '.jsx', '.py', '.java', '.cs', '.go', '.rs', '.rb',
    '.php', '.swift', '.kt', '.scala', '.c', '.cpp', '.h', '.hpp', '.cc',
    '.vue', '.svelte', '.dart', '.lua', '.r', '.pl', '.pm'
  ]);

  for (const commit of commits) {
    for (const file of commit.files) {
      if (analyzedFiles.has(file.path)) continue;
      if (EXCLUDED_DIRS.some(dir => file.path.startsWith(`${dir}/`) || file.path.includes(`/${dir}/`))) continue;
      analyzedFiles.add(file.path);

      const ext = '.' + (file.path.split('.').pop() || '');
      if (!codeExtensions.has(ext)) continue;

      const fullPath = `${repoPath}/${file.path}`;
      const fileResults = checkFileForTypos(fullPath);
      results.push(...fileResults);
    }
  }

  results.sort((a, b) => a.typo.localeCompare(b.typo));
  return results;
}

function checkFileForTypos(filePath: string): TypoResult[] {
  const results: TypoResult[] = [];

  try {
    readFileSync(filePath, 'utf-8');
  } catch {
    return results;
  }

  const content = readFileSync(filePath, 'utf-8');
  const lines = content.split('\n');

  const typoEntries = COMMON_TYPOS
    .filter(([typo]) => typo.length >= 3)
    .sort((a, b) => b[0].length - a[0].length);

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const comments = extractComments(line);

    for (const comment of comments) {
      const lowerComment = comment.toLowerCase();
      for (const [typo, suggestion] of typoEntries) {
        const idx = lowerComment.indexOf(typo);
        if (idx !== -1 && isWordBoundary(lowerComment, idx, typo.length)) {
          results.push({
            file: filePath,
            line: i + 1,
            column: idx + 1,
            typo,
            suggestion,
            context: line.trim().substring(0, 80),
          });
        }
      }
    }
  }

  return results;
}

function extractComments(line: string): string[] {
  const results: string[] = [];

  const singleLineComment = line.match(/\/\/\s*(.*)/);
  if (singleLineComment) results.push(singleLineComment[1]);

  const blockComment = line.match(/\/\*[\s\S]*?\*\//);
  if (blockComment) results.push(blockComment[0]);

  const pythonComment = line.match(/#\s*(.*)/);
  if (pythonComment) results.push(pythonComment[1]);

  return results;
}

function isWordBoundary(text: string, idx: number, length: number): boolean {
  const before = idx > 0 ? text[idx - 1] : ' ';
  const after = idx + length < text.length ? text[idx + length] : ' ';
  return !isLetter(before) && !isLetter(after);
}

function isLetter(c: string): boolean {
  return /[a-zA-Z]/.test(c);
}
